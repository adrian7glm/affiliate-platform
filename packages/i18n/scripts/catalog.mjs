// Lists the language files in src/locales and writes src/catalog.ts, so adding a language is
// adding its JSON file. `--check` fails instead of writing when the catalog is out of date.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'src', 'locales');
const out = join(root, 'src', 'catalog.ts');

const codes = readdirSync(dir)
  .filter((f) => f.endsWith('.json'))
  .map((f) => f.slice(0, -'.json'.length))
  .sort();
for (const code of codes) {
  if (!/^[a-z]{2,3}(-[a-z0-9]{2,8})?$/.test(code)) {
    throw new Error(
      `src/locales/${code}.json: name the file after a language code, e.g. de.json or pt-br.json`,
    );
  }
  JSON.parse(readFileSync(join(dir, `${code}.json`), 'utf8'));
}
if (!codes.includes('en'))
  throw new Error('src/locales/en.json is required: it is the reference language');

const ident = (code) => `lang_${code.replace(/-/g, '_')}`;
const content = [
  '// Generated by scripts/catalog.mjs from the files in src/locales. Do not edit by hand.',
  ...codes.map((c) => `import ${ident(c)} from './locales/${c}.json';`),
  '',
  'export const LOCALE_FILES = {',
  ...codes.map((c) => `  ${/-/.test(c) ? `'${c}'` : c}: ${ident(c)},`),
  '} as const;',
  '',
].join('\n');

let current = '';
try {
  current = readFileSync(out, 'utf8');
} catch {}
if (process.argv.includes('--check')) {
  if (current !== content) {
    console.error('src/catalog.ts is out of date: run `pnpm --filter @ap/i18n catalog`');
    process.exit(1);
  }
} else if (current !== content) {
  writeFileSync(out, content);
}
