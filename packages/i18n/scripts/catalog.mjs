// Lists the language files in src/locales and writes src/catalog.ts, src/languages.ts and
// src/loaders.ts, so adding a language is adding its JSON file. `--check` fails instead of writing when the catalog is out of date.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'src', 'locales');

const codes = readdirSync(dir)
  .filter((f) => f.endsWith('.json'))
  .map((f) => f.slice(0, -'.json'.length))
  .sort();
for (const code of codes) {
  if (!/^[a-z]{2,3}(-[a-z0-9]{2,8})?$/.test(code)) {
    throw new Error(
      `src/locales/${code}.json: name the file after a language code, e.g. de.json or pt-br.json`,
    );
  }
  JSON.parse(readFileSync(join(dir, `${code}.json`), 'utf8'));
}
if (!codes.includes('en'))
  throw new Error('src/locales/en.json is required: it is the reference language');

const ident = (code) => `lang_${code.replace(/-/g, '_')}`;
const key = (code) => (/-/.test(code) ? `'${code}'` : code);
const header =
  '// Generated by scripts/catalog.mjs from the files in src/locales. Do not edit by hand.';

const quote = (text) => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const infos = codes.map((code) => {
  const meta = JSON.parse(readFileSync(join(dir, `${code}.json`), 'utf8')).$language ?? {};
  return { code, name: meta.name ?? code, englishName: meta.englishName ?? code };
});

const outputs = {
  // Every file, for the API and server-rendered pages.
  'catalog.ts': [
    header,
    ...codes.map((c) => `import ${ident(c)} from './locales/${c}.json';`),
    '',
    'export const LOCALE_FILES = {',
    ...codes.map((c) => `  ${key(c)}: ${ident(c)},`),
    '} as const;',
    '',
  ],
  // Names only, so the language picker can list languages without loading their texts.
  'languages.ts': [
    header,
    '',
    'export const LOCALE_INFO = [',
    ...infos.map(
      (l) =>
        `  { code: '${l.code}', name: ${quote(l.name)}, englishName: ${quote(l.englishName)} },`,
    ),
    '] as const;',
    '',
  ],
  // One chunk per language for the web app (imported from source, see package.json exports).
  'loaders.ts': [
    header,
    '',
    'export const LOCALE_LOADERS: Record<string, () => Promise<{ default: unknown }>> = {',
    ...codes.map((c) => `  ${key(c)}: () => import('./locales/${c}.json'),`),
    '};',
    '',
  ],
};

let stale = false;
for (const [file, lines] of Object.entries(outputs)) {
  const target = join(root, 'src', file);
  const content = lines.join('\n');
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    // Not generated yet: write it below.
  }
  if (current === content) continue;
  if (process.argv.includes('--check')) {
    console.error(`src/${file} is out of date: run \`pnpm --filter @ap/i18n catalog\``);
    stale = true;
  } else {
    writeFileSync(target, content);
  }
}
if (stale) process.exit(1);
